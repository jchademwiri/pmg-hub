'use client';

import React, { useMemo, useState } from 'react';
import Link from 'next/link';
import { ExternalLink, Search } from 'lucide-react';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { Button } from '@/components/ui/button';
import { Badge } from '@/components/ui/badge';
import { Input } from '@/components/ui/input';
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from '@/components/ui/select';
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from '@/components/ui/table';
import { formatZAR, fmtDateLong } from '@/lib/format';
import type { RecurringInvoiceHistoryRow } from '@pmg/db';

interface BillingHistoryTabProps {
  historyInvoices: RecurringInvoiceHistoryRow[];
  divisions: { id: string; name: string }[];
}

const STATUS_BADGE: Record<string, string> = {
  paid: 'bg-emerald-500/10 text-emerald-700 dark:text-emerald-400 border-emerald-500/20',
  issued: 'bg-blue-500/10 text-blue-700 dark:text-blue-400 border-blue-500/20',
  partially_paid: 'bg-amber-500/10 text-amber-700 dark:text-amber-400 border-amber-500/20',
  overdue: 'bg-rose-500/10 text-rose-700 dark:text-rose-400 border-rose-500/20',
  void: 'bg-muted text-muted-foreground',
  draft: 'bg-muted text-muted-foreground',
};

export function BillingHistoryTab({ historyInvoices, divisions }: BillingHistoryTabProps) {
  const [search, setSearch] = useState('');
  const [divisionFilter, setDivisionFilter] = useState('all');
  const [statusFilter, setStatusFilter] = useState('all');

  const filtered = useMemo(() => {
    const q = search.trim().toLowerCase();
    return historyInvoices.filter((row) => {
      if (divisionFilter !== 'all' && row.divisionId !== divisionFilter) return false;
      if (statusFilter !== 'all' && row.status !== statusFilter) return false;
      if (!q) return true;
      return (
        row.documentNumber.toLowerCase().includes(q) ||
        row.clientName.toLowerCase().includes(q) ||
        (row.clientBusinessName ?? '').toLowerCase().includes(q) ||
        (row.recurringReference ?? '').toLowerCase().includes(q)
      );
    });
  }, [historyInvoices, search, divisionFilter, statusFilter]);

  return (
    <Card>
      <CardHeader className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-3">
        <div>
          <CardTitle className="text-base">Generated Retainer Invoices</CardTitle>
          <CardDescription>
            Official invoices automatically generated by recurring billing schedules.
          </CardDescription>
        </div>
        <Button variant="outline" size="sm" asChild>
          <Link href="/finance/expenses">
            View Logged Subscription Expenses <ExternalLink className="h-3.5 w-3.5 ml-1.5" />
          </Link>
        </Button>
      </CardHeader>

      <CardContent className="space-y-4">
        <div className="flex flex-wrap items-center gap-2">
          <div className="relative flex-1 min-w-[200px]">
            <Search className="h-4 w-4 text-muted-foreground absolute left-2.5 top-2.5" />
            <Input
              placeholder="Search invoice #, client, or reference..."
              value={search}
              onChange={(e) => setSearch(e.target.value)}
              className="pl-8 h-9"
            />
          </div>
          <Select value={divisionFilter} onValueChange={setDivisionFilter}>
            <SelectTrigger className="w-[170px] h-9">
              <SelectValue placeholder="All Divisions" />
            </SelectTrigger>
            <SelectContent>
              <SelectItem value="all">All Divisions</SelectItem>
              {divisions.map((d) => (
                <SelectItem key={d.id} value={d.id}>
                  {d.name}
                </SelectItem>
              ))}
            </SelectContent>
          </Select>
          <Select value={statusFilter} onValueChange={setStatusFilter}>
            <SelectTrigger className="w-[150px] h-9">
              <SelectValue placeholder="All Statuses" />
            </SelectTrigger>
            <SelectContent>
              <SelectItem value="all">All Statuses</SelectItem>
              <SelectItem value="issued">Issued</SelectItem>
              <SelectItem value="paid">Paid</SelectItem>
              <SelectItem value="partially_paid">Partially Paid</SelectItem>
              <SelectItem value="overdue">Overdue</SelectItem>
              <SelectItem value="void">Void</SelectItem>
            </SelectContent>
          </Select>
        </div>

        <div className="rounded-md border overflow-x-auto">
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>Invoice #</TableHead>
                <TableHead>Client</TableHead>
                <TableHead>Division</TableHead>
                <TableHead>Period / Date</TableHead>
                <TableHead>Status</TableHead>
                <TableHead className="text-right">Total</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {filtered.length === 0 ? (
                <TableRow>
                  <TableCell colSpan={6} className="text-center text-muted-foreground py-8">
                    No generated recurring invoices match your filters.
                  </TableCell>
                </TableRow>
              ) : (
                filtered.map((row) => (
                  <TableRow key={row.id}>
                    <TableCell className="font-mono text-xs font-medium">
                      <Link
                        href={`/billing/invoices/${row.id}`}
                        className="text-primary hover:underline"
                      >
                        {row.documentNumber}
                      </Link>
                    </TableCell>
                    <TableCell>
                      <div className="font-medium text-sm">
                        {row.clientBusinessName || row.clientName}
                      </div>
                      {row.recurringReference && (
                        <div className="text-xs text-muted-foreground">
                          {row.recurringReference}
                        </div>
                      )}
                    </TableCell>
                    <TableCell className="text-xs text-muted-foreground">
                      {row.divisionName}
                    </TableCell>
                    <TableCell className="text-xs">
                      <div>{fmtDateLong(row.invoiceDate)}</div>
                      {row.billingPeriod && (
                        <div className="text-muted-foreground">Cycle {row.billingPeriod}</div>
                      )}
                    </TableCell>
                    <TableCell>
                      <Badge
                        variant="outline"
                        className={STATUS_BADGE[row.status] ?? 'bg-muted text-muted-foreground'}
                      >
                        {row.status.replace('_', ' ')}
                      </Badge>
                    </TableCell>
                    <TableCell className="text-right font-mono font-medium tabular-nums">
                      {formatZAR(parseFloat(row.total) || 0)}
                    </TableCell>
                  </TableRow>
                ))
              )}
            </TableBody>
          </Table>
        </div>
      </CardContent>
    </Card>
  );
}
